export function getProductsBySection(section: string): Product[] {
  switch (section) {
    case 'daily':
      return mockProducts.slice(0, 8);
    case 'featured':
      return mockProducts.filter(p => p.badge === 'bestseller' || p.badge === 'new' || p.badge === 'exclusive').concat(mockProducts.slice(8, 12));
    case 'flash':
      return mockProducts.filter(p => (p.discountPercent ?? 0) >= 35).slice(0, 8);
    case 'trending':
      return mockProducts.filter(p => p.badge === 'trending' || p.rating >= 4.5).slice(0, 8);
    case 'recommended':
      return mockProducts.slice(4, 12);
    default:
      return mockProducts;
  }
}
